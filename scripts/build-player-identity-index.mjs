#!/usr/bin/env node
// scripts/build-player-identity-index.mjs
// Generates browser-consumable ES module at public/data/player-identities.js
// from data/entities/players.json.
// Zero timestamps, deterministic key ordering, compact gameplay runtime mapping only.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = path.resolve(__dirname, '..');
const PLAYERS_ENTITY_PATH = path.join(ROOT_DIR, 'data', 'entities', 'players.json');
const OUTPUT_PATH = path.join(ROOT_DIR, 'public', 'data', 'player-identities.js');

export function renderPlayerIdentityIndex() {
    if (!fs.existsSync(PLAYERS_ENTITY_PATH)) {
        throw new Error(`Missing player entities input file: ${PLAYERS_ENTITY_PATH}`);
    }

    const playersData = JSON.parse(fs.readFileSync(PLAYERS_ENTITY_PATH, 'utf8'));
    const entities = Array.isArray(playersData.entities) ? playersData.entities : [];

    const seasonToEntityFromEntities = new Map();
    const entityIds = new Set();

    for (const entity of entities) {
        if (!entity || typeof entity.id !== 'string' || entity.id.trim().length === 0) {
            throw new Error(`Invalid player entity id in ${PLAYERS_ENTITY_PATH}`);
        }
        if (entityIds.has(entity.id)) {
            throw new Error(`Duplicate player entity id: ${entity.id}`);
        }
        entityIds.add(entity.id);

        const seasonIds = Array.isArray(entity.playerSeasonIds) ? entity.playerSeasonIds : [];
        if (seasonIds.length === 0) {
            throw new Error(`Entity ${entity.id} has no playerSeasonIds`);
        }

        for (const psId of seasonIds) {
            if (typeof psId !== 'string' || psId.trim().length === 0) {
                throw new Error(`Invalid playerSeasonId in entity ${entity.id}`);
            }
            if (seasonToEntityFromEntities.has(psId)) {
                const prevOwner = seasonToEntityFromEntities.get(psId);
                throw new Error(
                    `Duplicate ownership for playerSeasonId "${psId}": "${prevOwner}" and "${entity.id}"`
                );
            }
            seasonToEntityFromEntities.set(psId, entity.id);
        }
    }

    const rawSeasonMap = playersData.playerSeasonMap || {};
    for (const [psId, entityId] of Object.entries(rawSeasonMap)) {
        const mappedEntity = seasonToEntityFromEntities.get(psId);
        if (!mappedEntity) {
            throw new Error(`playerSeasonMap key "${psId}" not found in entities[].playerSeasonIds`);
        }
        if (mappedEntity !== entityId) {
            throw new Error(
                `Mismatch for "${psId}": entities[] maps to "${mappedEntity}" vs playerSeasonMap "${entityId}"`
            );
        }
    }

    const sortedSeasonIds = Array.from(seasonToEntityFromEntities.keys()).sort((a, b) =>
        a.localeCompare(b)
    );

    const playerEntityBySeasonId = {};
    for (const psId of sortedSeasonIds) {
        playerEntityBySeasonId[psId] = seasonToEntityFromEntities.get(psId);
    }

    const lines = [
        '// AUTO-GENERATED by scripts/build-player-identity-index.mjs — DO NOT EDIT MANUALLY',
        '// Compact runtime identity index mapping PlayerSeason ID to canonical Player Entity ID.',
        '',
        `export const PLAYER_ENTITY_BY_SEASON_ID = ${JSON.stringify(playerEntityBySeasonId, null, 4)};`,
        '',
    ];

    return {
        entityCount: entityIds.size,
        playerSeasonCount: sortedSeasonIds.length,
        outputPath: OUTPUT_PATH,
        source: lines.join('\n'),
    };
}

export function buildPlayerIdentityIndex() {
    const rendered = renderPlayerIdentityIndex();
    fs.mkdirSync(path.dirname(rendered.outputPath), { recursive: true });
    fs.writeFileSync(rendered.outputPath, rendered.source, 'utf8');

    return {
        entityCount: rendered.entityCount,
        playerSeasonCount: rendered.playerSeasonCount,
        outputPath: rendered.outputPath,
    };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const res = buildPlayerIdentityIndex();
    console.log(
        `[build-player-identity-index] Wrote ${res.playerSeasonCount} PlayerSeason mappings across ${res.entityCount} canonical entities to public/data/player-identities.js`
    );
}
