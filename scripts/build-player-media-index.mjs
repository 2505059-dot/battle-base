#!/usr/bin/env node
// scripts/build-player-media-index.mjs
// Generates browser-consumable ES module at public/data/player-media.js
// from data/entities/player-media-resolutions.json.
// Zero timestamps, deterministic key ordering, compact runtime fields only.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = path.resolve(__dirname, '..');
const RESOLUTIONS_PATH = path.join(ROOT_DIR, 'data', 'entities', 'player-media-resolutions.json');
const OUTPUT_PATH = path.join(ROOT_DIR, 'public', 'data', 'player-media.js');

export const PLAYER_SILHOUETTE_URL = '/assets/player-silhouette.svg';

export function buildPlayerMediaIndex() {
    if (!fs.existsSync(RESOLUTIONS_PATH)) {
        throw new Error(`Missing resolution input file: ${RESOLUTIONS_PATH}`);
    }

    const resolutionsData = JSON.parse(fs.readFileSync(RESOLUTIONS_PATH, 'utf8'));
    const rawResolutions = resolutionsData.resolutions || {};
    const rawEntityDefaults = resolutionsData.entityDefaults || {};

    const playerSeasonMedia = {};
    const sortedSeasonIds = Object.keys(rawResolutions).sort((a, b) => a.localeCompare(b));

    for (const psId of sortedSeasonIds) {
        const entry = rawResolutions[psId];
        playerSeasonMedia[psId] = {
            entityId: entry.entityId,
            imageUrl: entry.imageUrl,
            provider: entry.provider,
            resolutionType: entry.resolutionType,
            sourceYear: entry.sourceYear ?? null,
            targetYear: entry.targetYear,
            licenseStatus: entry.licenseStatus,
        };
    }

    const playerEntityDefaultMedia = {};
    const sortedEntityIds = Object.keys(rawEntityDefaults).sort((a, b) => a.localeCompare(b));

    for (const entityId of sortedEntityIds) {
        const entry = rawEntityDefaults[entityId];
        playerEntityDefaultMedia[entityId] = {
            entityId: entry.entityId,
            imageUrl: entry.imageUrl,
            provider: entry.provider,
            resolutionType: entry.resolutionType,
            sourceYear: entry.sourceYear ?? null,
            targetYear: entry.targetYear,
            licenseStatus: entry.licenseStatus,
        };
    }

    const lines = [
        '// AUTO-GENERATED by scripts/build-player-media-index.mjs — DO NOT EDIT MANUALLY',
        '// Compact runtime index for PlayerSeason media and Player Entity default media.',
        '',
        `export const PLAYER_SILHOUETTE_URL = ${JSON.stringify(PLAYER_SILHOUETTE_URL)};`,
        '',
        `export const PLAYER_SEASON_MEDIA = ${JSON.stringify(playerSeasonMedia, null, 4)};`,
        '',
        `export const PLAYER_ENTITY_DEFAULT_MEDIA = ${JSON.stringify(playerEntityDefaultMedia, null, 4)};`,
        '',
    ];

    fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
    fs.writeFileSync(OUTPUT_PATH, lines.join('\n'), 'utf8');

    return {
        playerSeasonCount: sortedSeasonIds.length,
        entityCount: sortedEntityIds.length,
    };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const res = buildPlayerMediaIndex();
    console.log(
        `[build-player-media-index] Wrote ${res.playerSeasonCount} PlayerSeasons and ${res.entityCount} entity defaults to public/data/player-media.js`
    );
}
