#!/usr/bin/env node
// scripts/build-team-seasons.mjs
// Builds public/data/team-seasons.js from:
// - data/manual/season-pool.json (allowlist of 62 TeamSeasons)
// - data/raw/squads/squads-index.json (historical squad rosters)
// - data/raw/fifa/fifa-index.json (historical FIFA player attributes)
// - data/manual/club-aliases.json
// - data/manual/player-aliases.json
// - data/manual/overrides.json
// - data/manual/fallback-team-seasons.json
//
// Also outputs:
// - data/reports/build-report.json (full provenance per PlayerSeason)
// - data/reports/build-report.md (human-readable provenance & coverage summary)
// - data/reports/unresolved.json (all unverified or ambiguous records requiring attention)

