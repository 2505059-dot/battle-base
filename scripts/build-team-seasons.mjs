const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = path.resolve(__dirname, '..');
const MANUAL_DIR = path.join(ROOT_DIR, 'data', 'manual');
const RAW_SQUADS_INDEX = path.join(ROOT_DIR, 'data', 'raw', 'squads', 'squads-index.json');
const RAW_FIFA_INDEX = path.join(ROOT_DIR, 'data', 'raw', 'fifa', 'fifa-index.json');
const REPORTS_DIR = path.join(ROOT_DIR, 'data', 'reports');
const OUTPUT_JS_PATH = path.join(ROOT_DIR, 'public', 'data', 'team-seasons.js');

const LEAGUE_COMMENTS = {
    'Premier League': 'PREMIER LEAGUE',
    'La Liga': 'LA LIGA',
    'Serie A': 'SERIE A',
    'Bundesliga': 'BUNDESLIGA',
    'Ligue 1': 'LIGUE 1',
    'Eredivisie': 'EREDIVISIE',
    'Primeira Liga': 'PRIMEIRA LIGA',
};

function formatJsString(str) {
    if (str.includes("'") && !str.includes('"')) {
        return `"${str}"`;
    }
    return `'${str.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

function generateTeamSeasonsJsContent(builtTeamSeasons) {
    const lines = [
        '// 5-a-side Football Fantasy Draft — Historical Team-Season Dataset',
        '// Pure ES Module (no external dependencies)',
        '// Generated by scripts/build-team-seasons.mjs — DO NOT EDIT MANUALLY',
        '',
        'function p(name, positions, overall, attack, creation, defense, physical, goalkeeping) {',
        '    return {',
        '        name,',
        '        positions,',
        '        overall,',
        '        attack,',
        '        creation,',
        '        defense,',
        '        physical,',
        '        goalkeeping,',
        '    };',
        '}',
        '',
        'export const RAW_TEAM_SEASONS = [',
    ];

    let currentLeague = null;
    for (const ts of builtTeamSeasons) {
        if (ts.league !== currentLeague) {
            if (currentLeague !== null) {
                lines.push('');
            }
            currentLeague = ts.league;
            const header = LEAGUE_COMMENTS[currentLeague] || currentLeague.toUpperCase();
            lines.push('    // =========================================================================');
            lines.push(`    // ${header}`);
            lines.push('    // =========================================================================');
        }

        lines.push('    {');
        lines.push(`        id: ${formatJsString(ts.id)},`);
        lines.push(`        league: ${formatJsString(ts.league)},`);
        lines.push(`        club: ${formatJsString(ts.club)},`);
        lines.push(`        year: ${ts.year},`);
        lines.push('        players: [');
        for (const pl of ts.players) {
            const posArrayStr = `[${pl.positions.map((pos) => formatJsString(pos)).join(', ')}]`;
            lines.push(
                `            p(${formatJsString(pl.name)}, ${posArrayStr}, ${pl.overall}, ${pl.attack}, ${pl.creation}, ${pl.defense}, ${pl.physical}, ${pl.goalkeeping}),`
            );
        }
        lines.push('        ],');
        lines.push('    },');
    }

    lines.push('];');
    lines.push('');
    lines.push('// Normalize database so every player object has the exact upgraded schema');
    lines.push('export const TEAM_SEASONS = RAW_TEAM_SEASONS.map((ts) => ({');
    lines.push('    ...ts,');
    lines.push('    players: ts.players.map((player, index) => ({');
    lines.push('        id: `${ts.id}-${index}`,');
    lines.push('        name: player.name,');
    lines.push('        club: ts.club,');
    lines.push('        year: ts.year,');
    lines.push('        league: ts.league,');
    lines.push('        positions: [...player.positions],');
    lines.push('        overall: player.overall,');
    lines.push('        attack: player.attack,');
    lines.push('        creation: player.creation,');
    lines.push('        defense: player.defense,');
    lines.push('        physical: player.physical,');
    lines.push('        goalkeeping: player.goalkeeping,');
    lines.push('    })),');
    lines.push('}));');
    lines.push('');
    lines.push('// ---------- Structured Query Indexes ----------');
    lines.push('// Guarantees that all rolls and rerolls only ever produce valid (league, club, year) combinations');
    lines.push('');
    lines.push('export const TEAM_SEASON_MAP = new Map(TEAM_SEASONS.map((ts) => [ts.id, ts]));');
    lines.push('');
    lines.push('export const LEAGUES = [];');
    lines.push('export const CLUBS_BY_LEAGUE = new Map();       // league -> string[]');
    lines.push('export const YEARS_BY_LEAGUE_CLUB = new Map();  // `${league}::${club}` -> number[]');
    lines.push('export const TEAM_SEASON_BY_COMBO = new Map();  // `${league}::${club}::${year}` -> teamSeason');
    lines.push('');
    lines.push('for (const ts of TEAM_SEASONS) {');
    lines.push('    if (!LEAGUES.includes(ts.league)) {');
    lines.push('        LEAGUES.push(ts.league);');
    lines.push('    }');
    lines.push('');
    lines.push('    if (!CLUBS_BY_LEAGUE.has(ts.league)) {');
    lines.push('        CLUBS_BY_LEAGUE.set(ts.league, []);');
    lines.push('    }');
    lines.push('    const clubs = CLUBS_BY_LEAGUE.get(ts.league);');
    lines.push('    if (!clubs.includes(ts.club)) {');
    lines.push('        clubs.push(ts.club);');
    lines.push('    }');
    lines.push('');
    lines.push('    const lcKey = `${ts.league}::${ts.club}`;');
    lines.push('    if (!YEARS_BY_LEAGUE_CLUB.has(lcKey)) {');
    lines.push('        YEARS_BY_LEAGUE_CLUB.set(lcKey, []);');
    lines.push('    }');
    lines.push('    const years = YEARS_BY_LEAGUE_CLUB.get(lcKey);');
    lines.push('    if (!years.includes(ts.year)) {');
    lines.push('        years.push(ts.year);');
    lines.push('    }');
    lines.push('');
    lines.push('    TEAM_SEASON_BY_COMBO.set(`${ts.league}::${ts.club}::${ts.year}`, ts);');
    lines.push('}');
    lines.push('');
    lines.push('export function getLeagues() {');
    lines.push('    return LEAGUES;');
    lines.push('}');
    lines.push('');
    lines.push('export function getClubsByLeague(league) {');
    lines.push('    return CLUBS_BY_LEAGUE.get(league) ?? [];');
    lines.push('}');
    lines.push('');
    lines.push('export function getYearsByLeagueAndClub(league, club) {');
    lines.push('    return YEARS_BY_LEAGUE_CLUB.get(`${league}::${club}`) ?? [];');
    lines.push('}');
    lines.push('');
    lines.push('export function findTeamSeason(league, club, year) {');
    lines.push('    return TEAM_SEASON_BY_COMBO.get(`${league}::${club}::${year}`) ?? null;');
    lines.push('}');
    lines.push('');

    return lines.join('\r\n');
}

function matchRecordToCanonicalPlayer(recordNames, targetCanonical, playerAliasIndex) {
    for (const rawName of recordNames) {
        if (!rawName) continue;
        const res = canonicalizePlayerName(rawName, playerAliasIndex);
        if (res.canonicalName === targetCanonical) {
            return { matched: true, matchType: res.matchType, rawName };
        }
    }
    return { matched: false, matchType: 'none', rawName: null };
}

function deduplicateFifaCandidates(candidates) {
    // Group by source type + normalized longName + overall + age/positions to see if multiple distinct real players matched
    const bySource = new Map();
    for (const c of candidates) {
        const key = c.source;
        if (!bySource.has(key)) bySource.set(key, []);
        bySource.get(key).push(c);
    }
    return bySource;
}

export function runBuild() {
    fs.mkdirSync(REPORTS_DIR, { recursive: true });

    const seasonPool = JSON.parse(
        fs.readFileSync(path.join(MANUAL_DIR, 'season-pool.json'), 'utf8')
    );
    const fallbackSeasons = JSON.parse(
        fs.readFileSync(path.join(MANUAL_DIR, 'fallback-team-seasons.json'), 'utf8')
    );
    const clubAliases = JSON.parse(
        fs.readFileSync(path.join(MANUAL_DIR, 'club-aliases.json'), 'utf8')
    );
    const playerAliases = JSON.parse(
        fs.readFileSync(path.join(MANUAL_DIR, 'player-aliases.json'), 'utf8')
    );
    const overridesConfig = JSON.parse(
        fs.readFileSync(path.join(MANUAL_DIR, 'overrides.json'), 'utf8')
    );
    const overridesMap = overridesConfig.overrides || {};

    const squadsData = fs.existsSync(RAW_SQUADS_INDEX)
        ? JSON.parse(fs.readFileSync(RAW_SQUADS_INDEX, 'utf8')).entries || []
        : [];
    const fifaData = fs.existsSync(RAW_FIFA_INDEX)
        ? JSON.parse(fs.readFileSync(RAW_FIFA_INDEX, 'utf8')).records || []
        : [];

    // Collect all canonical clubs and players
    const knownClubs = [...new Set(seasonPool.map((s) => s.club))];
    const knownPlayers = [
        ...new Set(
            fallbackSeasons.flatMap((ts) => (ts.players || []).map((p) => p.name))
        ),
    ];

    const clubAliasIndex = buildAliasIndex(clubAliases, knownClubs);
    const playerAliasIndex = buildAliasIndex(playerAliases, knownPlayers);

    // Index fallback TeamSeasons by id and by (league::club::year)
    const fallbackById = new Map();
    for (const fts of fallbackSeasons) {
        fallbackById.set(fts.id, fts);
        fallbackById.set(`${fts.league}::${fts.club}::${fts.year}`, fts);
    }

    // Group squad entries by "club::year"
    const squadsByClubYear = new Map();
    for (const sq of squadsData) {
        const key = `${sq.club}::${sq.year}`;
        if (!squadsByClubYear.has(key)) squadsByClubYear.set(key, []);
        squadsByClubYear.get(key).push(sq);
    }

    // Group FIFA entries by "club::year" and by "year"
    const fifaByClubYear = new Map();
    const fifaByYear = new Map();
    for (const rec of fifaData) {
        if (rec.club) {
            const cyKey = `${rec.club}::${rec.year}`;
            if (!fifaByClubYear.has(cyKey)) fifaByClubYear.set(cyKey, []);
            fifaByClubYear.get(cyKey).push(rec);
        }
        if (!fifaByYear.has(rec.year)) fifaByYear.set(rec.year, []);
        fifaByYear.get(rec.year).push(rec);
    }

    const builtTeamSeasons = [];
    const playerReports = [];
    const unresolvedList = [];

    let verifiedExternalCount = 0;
    let manualOverrideCount = 0;
    let fallbackGeneratedCount = 0;

    for (const poolEntry of seasonPool) {
        const tsId =
            poolEntry.id ||
            `${poolEntry.club.toLowerCase().replace(/[^a-z0-9]+/g, '-')}-${poolEntry.year}`;
        const fallbackTs =
            fallbackById.get(tsId) ||
            fallbackById.get(`${poolEntry.league}::${poolEntry.club}::${poolEntry.year}`);

        const targetPlayers = fallbackTs ? fallbackTs.players : [];
        const clubYearKey = `${poolEntry.club}::${poolEntry.year}`;
        const clubSquadEntries = squadsByClubYear.get(clubYearKey) || [];
        const clubFifaEntries = fifaByClubYear.get(clubYearKey) || [];
        const yearFifaEntries = fifaByYear.get(poolEntry.year) || [];

        const builtPlayers = [];

        for (let idx = 0; idx < targetPlayers.length; idx++) {
            const targetPlayer = targetPlayers[idx];
            const canonicalName = targetPlayer.name;
            const playerSeasonId = `${tsId}-${idx}`;
            const overrideKey = `${tsId}::${canonicalName}`;
            const manualOverride = overridesMap[overrideKey] || null;

            // 1. Match Squad Membership
            const matchedSquadRecords = [];
            for (const sq of clubSquadEntries) {
                const m = matchRecordToCanonicalPlayer([sq.playerName], canonicalName, playerAliasIndex);
                if (m.matched) {
                    matchedSquadRecords.push({ ...sq, matchType: m.matchType });
                }
            }

            // 2. Match FIFA Attribute Records in (club, year)
            const sameClubFifaMatches = [];
            for (const fRec of clubFifaEntries) {
                const m = matchRecordToCanonicalPlayer(
                    [fRec.longName, fRec.shortName, fRec.aliasName],
                    canonicalName,
                    playerAliasIndex
                );
                if (m.matched) {
                    sameClubFifaMatches.push({ ...fRec, matchType: m.matchType, matchedRawName: m.rawName });
                }
            }

            let chosenFifa = null;
            let fifaMatchNote = null;
            let homonymConflict = false;

            // Check if sameClubFifaMatches has multiple distinct players in the same source
            const bySourceSameClub = deduplicateFifaCandidates(sameClubFifaMatches);
            for (const [, recs] of bySourceSameClub.entries()) {
                if (recs.length > 1) {
                    homonymConflict = true;
                }
            }

            if (!homonymConflict && sameClubFifaMatches.length > 0) {
                // Sort by sourcePriority ascending (1 first)
                const sorted = [...sameClubFifaMatches].sort((a, b) => a.sourcePriority - b.sourcePriority);
                for (const cand of sorted) {
                    const agg = aggregateAttributes(cand.tech);
                    if (agg) {
                        chosenFifa = { record: cand, aggregated: agg };
                        break;
                    }
                }
            }

            // 2B. If not found under (club, year) in FIFA, but verified in club's squad by ewenme/squads or footballcsv
            // (e.g. January transfer window signing or FIFA 05 club name variant), check yearFifaEntries with strict ambiguity guards
            if (!chosenFifa && !homonymConflict && matchedSquadRecords.length > 0) {
                const isSingleWordMononym = canonicalName.trim().split(/\s+/).length === 1;
                const yearMatches = [];

                for (const fRec of yearFifaEntries) {
                    // For single-word mononyms, require matching a multi-word alias in longName or exact club match
                    const candidateNames = isSingleWordMononym
                        ? [fRec.longName]
                        : [fRec.longName, fRec.shortName, fRec.aliasName];
                    const m = matchRecordToCanonicalPlayer(candidateNames, canonicalName, playerAliasIndex);
                    if (m.matched) {
                        if (isSingleWordMononym && fRec.longName.trim().split(/\s+/).length === 1) {
                            continue; // Never cross-club match a 1-word mononym against a 1-word FIFA name
                        }
                        yearMatches.push({ ...fRec, matchType: m.matchType });
                    }
                }

                const bySourceYear = deduplicateFifaCandidates(yearMatches);
                let ambiguousAcrossYear = false;
                for (const [, recs] of bySourceYear.entries()) {
                    if (recs.length > 1) {
                        ambiguousAcrossYear = true;
                    }
                }

                if (ambiguousAcrossYear) {
                    homonymConflict = true;
                } else if (yearMatches.length > 0) {
                    const sorted = [...yearMatches].sort((a, b) => a.sourcePriority - b.sourcePriority);
                    for (const cand of sorted) {
                        const agg = aggregateAttributes(cand.tech);
                        if (agg) {
                            chosenFifa = { record: cand, aggregated: agg };
                            fifaMatchNote = `squad-verified mid-season/roster match (FIFA club: ${cand.rawClub || 'N/A'})`;
                            break;
                        }
                    }
                }
            }

            // Determine Squad Source
            let squadSource = null;
            if (matchedSquadRecords.length > 0) {
                const sources = [...new Set(matchedSquadRecords.map((r) => r.source))];
                squadSource = sources.join(' + ');
            } else if (chosenFifa && chosenFifa.record.club === poolEntry.club) {
                squadSource = chosenFifa.record.source;
            }

            // Check if there was a fuzzy candidate when unmatched
            let fuzzySuggestion = null;
            if (!squadSource) {
                let bestSim = 0;
                let bestCand = null;
                for (const sq of clubSquadEntries) {
                    const sim = computeNameSimilarity(canonicalName, sq.playerName);
                    if (sim > bestSim) {
                        bestSim = sim;
                        bestCand = `${sq.playerName} (${sq.source})`;
                    }
                }
                for (const fRec of clubFifaEntries) {
                    for (const nm of [fRec.longName, fRec.shortName]) {
                        const sim = computeNameSimilarity(canonicalName, nm);
                        if (sim > bestSim) {
                            bestSim = sim;
                            bestCand = `${nm} (${fRec.source})`;
                        }
                    }
                }
                if (bestSim >= 0.72) {
                    fuzzySuggestion = { candidate: bestCand, similarity: Number(bestSim.toFixed(3)) };
                }
            }

            // Determine Positions
            let finalPositions = [...targetPlayer.positions];
            let positionSource = 'fallback-generated';

            const extPositions = [];
            if (chosenFifa && chosenFifa.record.positions.length > 0) {
                for (const p of chosenFifa.record.positions) {
                    if (!extPositions.includes(p)) extPositions.push(p);
                }
                positionSource = chosenFifa.record.source;
            }
            if (matchedSquadRecords.length > 0) {
                for (const sq of matchedSquadRecords) {
                    for (const p of sq.positions) {
                        if (!extPositions.includes(p)) extPositions.push(p);
                    }
                }
                if (positionSource === 'fallback-generated' && extPositions.length > 0) {
                    positionSource = matchedSquadRecords[0].source;
                }
            }
            // Enforce GK exclusivity; if external position comes solely from single-code squad files
            // (footballcsv G/D/M/F) and agrees with baseline primary position, retain baseline secondary positions.
            if (
                !chosenFifa &&
                extPositions.length === 1 &&
                targetPlayer.positions.length > 1 &&
                targetPlayer.positions.includes(extPositions[0])
            ) {
                for (const p of targetPlayer.positions) {
                    if (!extPositions.includes(p)) extPositions.push(p);
                }
            }
            const normalizedExtPos = normalizePositions(extPositions);
            if (normalizedExtPos.length > 0) {
                finalPositions = normalizedExtPos;
            }

            // Determine Attributes
            let finalStats = {
                overall: targetPlayer.overall,
                attack: targetPlayer.attack,
                creation: targetPlayer.creation,
                defense: targetPlayer.defense,
                physical: targetPlayer.physical,
                goalkeeping: targetPlayer.goalkeeping,
            };
            let overallSource = 'fallback-generated';
            let technicalSource = 'fallback-generated';

            if (chosenFifa) {
                finalStats = { ...chosenFifa.aggregated };
                const srcLabel = fifaMatchNote
                    ? `${chosenFifa.record.source} [${fifaMatchNote}]`
                    : chosenFifa.record.source;
                overallSource = srcLabel;
                technicalSource = srcLabel;
            }

            // Apply Manual Overrides if present
            const overrideFields = [];
            let overrideUsed = false;
            let overrideReason = null;

            if (manualOverride) {
                overrideUsed = true;
                overrideReason = manualOverride.reason || null;
                if (Array.isArray(manualOverride.positions) && manualOverride.positions.length > 0) {
                    finalPositions = normalizePositions(manualOverride.positions);
                    overrideFields.push('positions');
                    positionSource = 'manual-override';
                }
                for (const statKey of ['overall', 'attack', 'creation', 'defense', 'physical', 'goalkeeping']) {
                    if (manualOverride[statKey] !== undefined) {
                        finalStats[statKey] = clampStat(manualOverride[statKey]);
                        overrideFields.push(statKey);
                        if (statKey === 'overall') overallSource = 'manual-override';
                        else technicalSource = 'manual-override';
                    }
                }
                if (manualOverride.squadVerifiedByOverride && !squadSource) {
                    squadSource = 'manual-override';
                    overrideFields.push('squad');
                }
            }

            // Classify final status
            const isExternalVerified =
                Boolean(squadSource) &&
                squadSource !== 'fallback-generated' &&
                overallSource !== 'fallback-generated' &&
                technicalSource !== 'fallback-generated';

            let status = 'fallback-generated';
            let fallbackUsed = false;

            if (overrideUsed) {
                status = 'manual-override';
                manualOverrideCount++;
            } else if (isExternalVerified) {
                status = 'verified-external';
                verifiedExternalCount++;
            } else {
                status = 'fallback-generated';
                fallbackUsed = true;
                fallbackGeneratedCount++;
            }

            if (!squadSource) {
                squadSource = 'fallback-generated';
            }

            // Record unresolved details whenever external verification is incomplete and not manually overridden
            if (!isExternalVerified && !overrideUsed) {
                const reasons = [];
                if (squadSource === 'fallback-generated') {
                    reasons.push('unmatched_squad_player');
                }
                if (homonymConflict) {
                    reasons.push('ambiguous_homonym_collision');
                } else if (poolEntry.year < 2005) {
                    reasons.push('season_predates_fifa_05_dataset');
                } else if (overallSource === 'fallback-generated') {
                    reasons.push('unmatched_fifa_player_or_incomplete_attributes');
                }
                if (fuzzySuggestion) {
                    reasons.push('fuzzy_match_uncertain');
                }

                unresolvedList.push({
                    id: playerSeasonId,
                    teamSeasonId: tsId,
                    league: poolEntry.league,
                    club: poolEntry.club,
                    year: poolEntry.year,
                    playerName: canonicalName,
                    reasons,
                    squadSource,
                    overallSource,
                    fuzzySuggestion,
                });
            }

            builtPlayers.push({
                name: canonicalName,
                positions: finalPositions,
                overall: finalStats.overall,
                attack: finalStats.attack,
                creation: finalStats.creation,
                defense: finalStats.defense,
                physical: finalStats.physical,
                goalkeeping: finalStats.goalkeeping,
            });

            playerReports.push({
                id: playerSeasonId,
                teamSeasonId: tsId,
                name: canonicalName,
                club: poolEntry.club,
                year: poolEntry.year,
                league: poolEntry.league,
                positions: finalPositions,
                overall: finalStats.overall,
                attack: finalStats.attack,
                creation: finalStats.creation,
                defense: finalStats.defense,
                physical: finalStats.physical,
                goalkeeping: finalStats.goalkeeping,
                status,
                provenance: {
                    squadSource,
                    positionSource,
                    overallSource,
                    technicalSource,
                    overrideUsed,
                    overrideFields,
                    overrideReason,
                    fallbackUsed,
                },
            });
        }

        builtTeamSeasons.push({
            id: tsId,
            league: poolEntry.league,
            club: poolEntry.club,
            year: poolEntry.year,
            players: builtPlayers,
        });
    }

    // Write public/data/team-seasons.js
    const jsContent = generateTeamSeasonsJsContent(builtTeamSeasons);
    fs.writeFileSync(OUTPUT_JS_PATH, jsContent, 'utf8');

    const totalPlayers = playerReports.length;
    const squadVerifiedCount = playerReports.filter(
        (p) => p.provenance.squadSource !== 'fallback-generated'
    ).length;

    const summary = {
        pipelineVersion: '1.0.0',
        teamSeasonsCount: builtTeamSeasons.length,
        playerSeasonsCount: totalPlayers,
        counts: {
            verifiedExternal: verifiedExternalCount,
            manualOverride: manualOverrideCount,
            fallbackGenerated: fallbackGeneratedCount,
            unresolved: unresolvedList.length,
            squadRosterVerified: squadVerifiedCount,
        },
        percentages: {
            verifiedExternalPct: Number(((verifiedExternalCount / totalPlayers) * 100).toFixed(2)),
            manualOverridePct: Number(((manualOverrideCount / totalPlayers) * 100).toFixed(2)),
            fallbackGeneratedPct: Number(((fallbackGeneratedCount / totalPlayers) * 100).toFixed(2)),
            squadRosterVerifiedPct: Number(((squadVerifiedCount / totalPlayers) * 100).toFixed(2)),
        },
    };

    // Write data/reports/build-report.json
    const buildReportPath = path.join(REPORTS_DIR, 'build-report.json');
    fs.writeFileSync(
        buildReportPath,
        JSON.stringify(
            {
                summary,
                attributeWeights: ATTRIBUTE_WEIGHTS,
                players: playerReports,
            },
            null,
            2
        ) + '\n',
        'utf8'
    );

    // Write data/reports/unresolved.json
    const unresolvedPath = path.join(REPORTS_DIR, 'unresolved.json');
    fs.writeFileSync(
        unresolvedPath,
        JSON.stringify(
            {
                pipelineVersion: summary.pipelineVersion,
                totalUnresolved: unresolvedList.length,
                items: unresolvedList,
            },
            null,
            2
        ) + '\n',
        'utf8'
    );

    // Write human-readable data/reports/build-report.md
    const mdLines = [
        '# Team-Seasons Build & Provenance Report',
        '',
        `- **Total TeamSeasons**: ${summary.teamSeasonsCount}`,
        `- **Total PlayerSeasons**: ${summary.playerSeasonsCount}`,
        `- **Squad Roster Externally Verified**: ${summary.counts.squadRosterVerified} / ${totalPlayers} (${summary.percentages.squadRosterVerifiedPct}%)`,
        `- **Full External Verified (Squad + FIFA Ratings)**: ${summary.counts.verifiedExternal} / ${totalPlayers} (${summary.percentages.verifiedExternalPct}%)`,
        `- **Manual Overrides**: ${summary.counts.manualOverride} / ${totalPlayers} (${summary.percentages.manualOverridePct}%)`,
        `- **Fallback-Generated**: ${summary.counts.fallbackGenerated} / ${totalPlayers} (${summary.percentages.fallbackGeneratedPct}%)`,
        `- **Unresolved Records**: ${summary.counts.unresolved}`,
        '',
        '## Sample Provenance Check: Cristiano Ronaldo / Manchester United / 2008',
        '',
    ];

    const ronaldo2008 = playerReports.find(
        (p) => p.name === 'Cristiano Ronaldo' && p.club === 'Manchester United' && p.year === 2008
    );
    if (ronaldo2008) {
        mdLines.push('```json');
        mdLines.push(JSON.stringify(ronaldo2008, null, 2));
        mdLines.push('```');
    }

    mdLines.push('');
    mdLines.push('## Season-by-Season Coverage Breakdown');
    mdLines.push('');
    mdLines.push('| TeamSeason ID | League | Club | Year | Total | Verified External | Manual Override | Fallback |');
    mdLines.push('| :--- | :--- | :--- | :--- | :---: | :---: | :---: | :---: |');

    for (const ts of builtTeamSeasons) {
        const tsPlayers = playerReports.filter((p) => p.teamSeasonId === ts.id);
        const vExt = tsPlayers.filter((p) => p.status === 'verified-external').length;
        const mOvr = tsPlayers.filter((p) => p.status === 'manual-override').length;
        const fGen = tsPlayers.filter((p) => p.status === 'fallback-generated').length;
        mdLines.push(
            `| \`${ts.id}\` | ${ts.league} | ${ts.club} | ${ts.year} | ${tsPlayers.length} | ${vExt} | ${mOvr} | ${fGen} |`
        );
    }

    fs.writeFileSync(path.join(REPORTS_DIR, 'build-report.md'), mdLines.join('\n') + '\n', 'utf8');

    return { summary, unresolvedList, playerReports };
}

